package com.ibadalrahman.app.data

import kotlin.math.asin
import kotlin.math.cos
import kotlin.math.sin
import kotlin.math.sqrt

data class City(
    /** Stable identifier persisted in settings: "<country code>:<Arabic name>". */
    val id: String,
    val name: String,
    val country: String,
    val countryCode: String,
    val latitude: Double,
    val longitude: Double,
    val zoneId: String,
)

/** Offline list of cities so the app works without GPS or network. */
object Cities {

    val all: List<City> by lazy { build() }

    val countries: List<Pair<String, String>> by lazy {
        all.map { it.countryCode to it.country }.distinct()
    }

    fun byId(id: String): City? = all.firstOrNull { it.id == id }

    fun search(query: String): List<City> {
        val q = normalize(query.trim())
        if (q.isEmpty()) return all
        return all.filter { normalize(it.name).contains(q) || normalize(it.country).contains(q) }
    }

    fun nearest(latitude: Double, longitude: Double, maxKm: Double = 60.0): City? =
        all.minByOrNull { distanceKm(latitude, longitude, it.latitude, it.longitude) }
            ?.takeIf { distanceKm(latitude, longitude, it.latitude, it.longitude) <= maxKm }

    /** Folds Arabic letter variants and strips diacritics so searching is forgiving. */
    fun normalize(s: String): String = buildString(s.length) {
        for (ch in s.lowercase()) {
            when (ch) {
                'أ', 'إ', 'آ', 'ٱ' -> append('ا')
                'ة' -> append('ه')
                'ى' -> append('ي')
                'ؤ' -> append('و')
                'ئ' -> append('ي')
                in 'ً'..'ٟ', 'ٰ', 'ـ' -> Unit
                else -> append(ch)
            }
        }
    }

    private fun distanceKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val p1 = Math.toRadians(lat1)
        val p2 = Math.toRadians(lat2)
        val dp = p2 - p1
        val dl = Math.toRadians(lon2 - lon1)
        val a = sin(dp / 2) * sin(dp / 2) + cos(p1) * cos(p2) * sin(dl / 2) * sin(dl / 2)
        return 2 * 6371.0 * asin(sqrt(a))
    }

    private class CountryScope(
        val code: String,
        val name: String,
        val zone: String,
        val out: MutableList<City>,
    ) {
        fun c(cityName: String, lat: Double, lng: Double, zoneId: String = zone) {
            out += City("$code:$cityName", cityName, name, code, lat, lng, zoneId)
        }
    }

    private fun MutableList<City>.country(code: String, name: String, zone: String, block: CountryScope.() -> Unit) {
        CountryScope(code, name, zone, this).block()
    }

